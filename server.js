/**
 * masonnguyengeo.com — Node.js Server
 * Express + GEO signal files + security + caching
 * Hostinger Node.js deployment ready
 */

'use strict';

const express    = require('express');
const helmet     = require('helmet');
const compression = require('compression');
const morgan     = require('morgan');
const rateLimit  = require('express-rate-limit');
const path       = require('path');
const fs         = require('fs');

const app  = express();
const PORT = process.env.PORT || 3000;
const HOST = process.env.HOST || '0.0.0.0';
const ENV  = process.env.NODE_ENV || 'production';

// ─── SECURITY ─────────────────────────────────────────────────────────────────
app.use(helmet({
  contentSecurityPolicy: {
    directives: {
      defaultSrc:  ["'self'"],
      scriptSrc:   ["'self'", "'unsafe-inline'", "https://fonts.googleapis.com"],
      styleSrc:    ["'self'", "'unsafe-inline'", "https://fonts.googleapis.com", "https://fonts.gstatic.com"],
      fontSrc:     ["'self'", "https://fonts.gstatic.com"],
      imgSrc:      ["'self'", "data:", "https:"],
      connectSrc:  ["'self'"],
      frameSrc:    ["'none'"],
      objectSrc:   ["'none'"],
    },
  },
  hsts: { maxAge: 31536000, includeSubDomains: true, preload: true },
  referrerPolicy: { policy: 'strict-origin-when-cross-origin' },
}));

// ─── COMPRESSION ──────────────────────────────────────────────────────────────
app.use(compression({ level: 6 }));

// ─── LOGGING ──────────────────────────────────────────────────────────────────
if (ENV !== 'test') {
  app.use(morgan(ENV === 'production' ? 'combined' : 'dev'));
}

// ─── RATE LIMITING ────────────────────────────────────────────────────────────
const limiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 min
  max: 200,
  standardHeaders: true,
  legacyHeaders: false,
  message: 'Too many requests — please try again shortly.',
});
app.use(limiter);

// ─── TRUST PROXY (Hostinger uses reverse proxy) ───────────────────────────────
app.set('trust proxy', 1);

// ─── CANONICAL REDIRECT ───────────────────────────────────────────────────────
// Redirect the bare domain → www, which is the production primary host.
app.use((req, res, next) => {
  if (req.hostname === 'masonnguyengeo.com') {
    const canonical = `https://www.masonnguyengeo.com${req.originalUrl}`;
    return res.redirect(301, canonical);
  }
  // Force HTTPS in production
  if (ENV === 'production' && req.headers['x-forwarded-proto'] === 'http') {
    return res.redirect(301, `https://${req.hostname}${req.originalUrl}`);
  }
  next();
});

