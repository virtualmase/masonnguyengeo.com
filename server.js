// ─── STATIC FILES ─────────────────────────────────────────────────────────────
// Serve root-level content directories (what-is-geo/, arm-framework/, etc.)
const staticOpts = {
  maxAge: ENV === 'production' ? '7d' : 0,
  etag: true,
  lastModified: true,
  index: 'index.html',
};
app.use(express.static(path.join(__dirname), staticOpts));

app.use(express.static(path.join(__dirname, 'public'), {
  maxAge: ENV === 'production' ? '7d' : 0,
  etag: true,
  lastModified: true,
  setHeaders(res, filePath) {
    // Aggressive caching for font/image assets
    if (/\.(woff2?|ttf|otf|eot)$/.test(filePath)) {
      res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
    }
    if (/\.(png|jpg|jpeg|webp|avif|svg|ico)$/.test(filePath)) {
      res.setHeader('Cache-Control', 'public, max-age=604800');
    }
    if (/\.(css|js)$/.test(filePath)) {
      res.setHeader('Cache-Control', 'public, max-age=86400');
    }
    // GEO-critical: Allow all LLM crawlers on all assets
    res.setHeader('X-Robots-Tag', 'index, follow');
  },
}));

// ─── SPA FALLBACK — serve index.html for any unmatched route ──────────────────
app.get('*', (req, res) => {
  res.sendFile(path.join(__dirname, 'public', 'index.html'));
});

// ─── ERROR HANDLER ────────────────────────────────────────────────────────────
app.use((err, req, res, next) => {
  console.error(`[ERROR] ${err.status || 500} — ${err.message}`);
  res.status(err.status || 500).json({
    error: ENV === 'production' ? 'Internal server error' : err.message,
  });
});

